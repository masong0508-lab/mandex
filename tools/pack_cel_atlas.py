#!/usr/bin/env python3
"""Extract character-only, namespace-safe runtime data from isolated Cel bakes.

Do not ship a second title, backdrop or world atlas. Keep the Classic frame
enum and indexed palette contract; only the alternate pose geometry, pixels
and hand metadata change. The existing Dreamcast texture sizes stay fixed.
"""
import re
import sys
from pathlib import Path

def array(src, name):
    matches = re.findall(
        r"^static const [^\n]+\b" + re.escape(name) +
        r"\[[^\n]*?\]\s*=\s*\{.*?^\};", src, re.M | re.S
    )
    if len(matches) != 1:
        raise ValueError(f"expected exactly one array {name}, got {len(matches)}")
    return matches[0]

def constant(src, name):
    m = re.search(r"^#define " + re.escape(name) + r"\s+(\d+)\b", src, re.M)
    if not m:
        raise ValueError(f"missing {name}")
    return int(m[1])

def require_equal(src, classic, names):
    for name in names:
        if constant(src, name) != constant(classic, name):
            raise ValueError(f"changed atlas contract: {name}")

def build(preview, art):
    indexed = (preview / "manspr-cel-preview.h").read_text()
    hd = (preview / "dcart-cel-preview.h").read_text()
    classic = (art / "manspr.h").read_text()
    classic_hd = (art / "dcart.h").read_text()
    require_equal(indexed, classic, ("MS_NPAL", "MSF_NBASE"))
    require_equal(hd, classic_hd, ("DCM_NFR", "DCT_MAN_W", "DCT_MAN_H",
                                 "DCT_WMAN_W", "DCT_WMAN_H"))
    if re.search(r"^enum \{.*?MSF_COUNT \};", indexed, re.M)[0] != re.search(r"^enum \{.*?MSF_COUNT \};", classic, re.M)[0]:
        raise ValueError("frame IDs or order changed")
    # The indexed renderer uses the existing per-outfit palette indices.
    for name in ("MS_PAL", "MS_CL_COL"):
        if array(indexed, name) != array(classic, name):
            raise ValueError(f"indexed palette changed: {name}")
    names = re.findall(r"^static const unsigned char (MS_\w+)\[\d+\] = \{", indexed, re.M)
    if len(names) != 2 * constant(indexed, "MSF_NBASE"):
        raise ValueError("wrong indexed frame count")
    # Only the actual sprite arrays and their metadata; reuse MsFrame.
    data = "\n".join(array(indexed, name) for name in names + ["MS_FRAMES", "MS_HAND"])
    data = re.sub(r"\bMS_(\w+)\b", r"MC_\1", data)
    (art / "manspr_cel.h").write_text(
        "/* generated by pack_cel_atlas.py; include after manspr.h */\n"
        "#ifndef MX_GENERATED_MANSPR_CEL_H\n#define MX_GENERATED_MANSPR_CEL_H\n"
        + data + "\n#endif\n"
    )
    # No duplicate scenery, font, title or textures in the native binary.
    defs = []
    arrays = []
    for name in ("MAN", "WMAN"):
        key = f"DCT_{name}_RLE"
        defs.append(f"#define MC_{key}_LEN {constant(hd, key + '_LEN')}")
        arrays.append(array(hd, key).replace(key, "MC_" + key))
    arrays.append(array(hd, "DCM_FR").replace("DCM_FR", "MC_DCM_FR"))
    arrays.append(array(indexed, "MS_HAND").replace("MS_HAND", "MC_DC_HAND"))
    scale = re.search(r"^#define DCM_SCALE ([^\s]+)", hd, re.M)[1]
    if scale != re.search(r"^#define DCM_SCALE ([^\s]+)", classic_hd, re.M)[1]:
        raise ValueError("Dreamcast drawing scale changed")
    (art / "dcart_cel.h").write_text(
        "/* generated by pack_cel_atlas.py; include after dcart.h */\n"
        "#ifndef MX_GENERATED_DCART_CEL_H\n#define MX_GENERATED_DCART_CEL_H\n"
        + "\n".join(defs + arrays) + "\n#endif\n"
    )
    print(f"Packed {len(names)} alternate indexed and HD character poses")

if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit("usage: pack_cel_atlas.py preview-directory art-directory")
    build(Path(sys.argv[1]), Path(sys.argv[2]))
